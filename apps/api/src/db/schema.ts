// Typed view of migrations/*.sql for Drizzle queries. The SQL files are the source of truth (they
// carry RLS policies and grants); test/integration/migrations.int-spec.ts checks the two agree.
import { sql } from 'drizzle-orm';
import {
  bigint,
  boolean,
  customType,
  integer,
  jsonb,
  pgSchema,
  smallint,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';

const bytea = customType<{ data: Uint8Array; driverData: Buffer }>({
  dataType: () => 'bytea',
  toDriver: (value) => Buffer.from(value.buffer, value.byteOffset, value.byteLength),
  fromDriver: (value) => new Uint8Array(value),
});

const timestamptz = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

export const app = pgSchema('app');

/** Time-ordered ids generated by Postgres 18. */
const uuidv7 = sql`uuidv7()`;

export const platform = app.enum('platform', ['ios', 'android']);
export const attestationKind = app.enum('attestation_kind', ['app_attest', 'play_integrity']);
export const revocationReason = app.enum('revocation_reason', [
  'replaced',
  'logout',
  'remote',
  'refresh_reuse',
]);

export const users = app.table('users', {
  id: uuid('id').primaryKey(),
  emailHmac: bytea('email_hmac').notNull(),
  username: text('username'),
  displayName: text('display_name'),
  avatarColor: smallint('avatar_color'),
  avatarEmoji: text('avatar_emoji'),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  deletedAt: timestamptz('deleted_at'),
});

export const devices = app.table('devices', {
  id: uuid('id').primaryKey(),
  userId: uuid('user_id').notNull(),
  platform: platform('platform').notNull(),
  identityKey: bytea('identity_key').notNull(),
  dhKey: bytea('dh_key').notNull(),
  dhKeySignature: bytea('dh_key_signature').notNull(),
  attestation: attestationKind('attestation'),
  attestedAt: timestamptz('attested_at'),
  pushToken: text('push_token'),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  lastSeenAt: timestamptz('last_seen_at').notNull().defaultNow(),
  revokedAt: timestamptz('revoked_at'),
  revokedReason: revocationReason('revoked_reason'),
});

export const passkeys = app.table('passkeys', {
  credentialId: bytea('credential_id').primaryKey(),
  userId: uuid('user_id').notNull(),
  publicKey: bytea('public_key').notNull(),
  counter: bigint('counter', { mode: 'number' }).notNull().default(0),
  transports: text('transports').array().notNull().default([]),
  backedUp: boolean('backed_up').notNull(),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  lastUsedAt: timestamptz('last_used_at'),
});

export const refreshTokens = app.table('refresh_tokens', {
  id: uuid('id').primaryKey().default(uuidv7),
  userId: uuid('user_id').notNull(),
  deviceId: uuid('device_id').notNull(),
  familyId: uuid('family_id').notNull(),
  tokenHash: bytea('token_hash').notNull(),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  expiresAt: timestamptz('expires_at').notNull(),
  usedAt: timestamptz('used_at'),
  replacedBy: uuid('replaced_by'),
  revokedAt: timestamptz('revoked_at'),
});

export const securityEventTypes = [
  'login_otp',
  'login_passkey',
  'device_replaced',
  'refresh_reuse',
  'passkey_added',
  'logout',
] as const;
export type SecurityEventType = (typeof securityEventTypes)[number];

export const securityEvents = app.table('security_events', {
  id: uuid('id').primaryKey().default(uuidv7),
  userId: uuid('user_id').notNull(),
  type: text('type', { enum: securityEventTypes }).notNull(),
  deviceId: uuid('device_id'),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
});

export const circleKind = app.enum('circle_kind', ['pair', 'friends', 'family', 'event']);
export const memberRole = app.enum('member_role', ['owner', 'member']);
export const memberStatus = app.enum('member_status', [
  'invited',
  'active',
  'declined',
  'left',
  'removed',
]);
export const inviteKind = app.enum('invite_kind', ['circle', 'friend']);

export const circles = app.table('circles', {
  id: uuid('id').primaryKey().default(uuidv7),
  kind: circleKind('kind').notNull(),
  name: text('name'),
  pairKey: text('pair_key'),
  epoch: integer('epoch').notNull().default(1),
  epochStartedAt: timestamptz('epoch_started_at').notNull().defaultNow(),
  expiresAt: timestamptz('expires_at'),
  createdBy: uuid('created_by'),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
});

export const circleMembers = app.table('circle_members', {
  circleId: uuid('circle_id').notNull(),
  userId: uuid('user_id').notNull(),
  role: memberRole('role').notNull().default('member'),
  status: memberStatus('status').notNull(),
  invitedBy: uuid('invited_by'),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  joinedAt: timestamptz('joined_at'),
  endedAt: timestamptz('ended_at'),
});

export const invites = app.table('invites', {
  id: uuid('id').primaryKey().default(uuidv7),
  kind: inviteKind('kind').notNull(),
  circleId: uuid('circle_id'),
  tokenHash: bytea('token_hash').notNull(),
  createdBy: uuid('created_by').notNull(),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
  expiresAt: timestamptz('expires_at').notNull(),
  maxUses: integer('max_uses').notNull().default(1),
  usedCount: integer('used_count').notNull().default(0),
  revokedAt: timestamptz('revoked_at'),
});

export const keyEnvelopes = app.table('key_envelopes', {
  circleId: uuid('circle_id').notNull(),
  epoch: integer('epoch').notNull(),
  senderDeviceId: uuid('sender_device_id').notNull(),
  recipientDeviceId: uuid('recipient_device_id').notNull(),
  senderUserId: uuid('sender_user_id').notNull(),
  recipientUserId: uuid('recipient_user_id').notNull(),
  envelope: jsonb('envelope').notNull(),
  createdAt: timestamptz('created_at').notNull().defaultNow(),
});

export const pushTokens = app.table('push_tokens', {
  deviceId: uuid('device_id').primaryKey(),
  userId: uuid('user_id').notNull(),
  tokenSealed: text('token_sealed').notNull(),
  locale: text('locale', { enum: ['tr', 'en'] }).notNull(),
  updatedAt: timestamptz('updated_at').notNull().defaultNow(),
});

export const profilePhotos = app.table('profile_photos', {
  userId: uuid('user_id').primaryKey(),
  photoId: uuid('photo_id').notNull(),
  ciphertext: bytea('ciphertext').notNull(),
  updatedAt: timestamptz('updated_at').notNull().defaultNow(),
});

export const schema = {
  users,
  devices,
  passkeys,
  refreshTokens,
  securityEvents,
  circles,
  circleMembers,
  invites,
  keyEnvelopes,
  pushTokens,
  profilePhotos,
};
