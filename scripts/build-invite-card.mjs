// Renders the invite card image (the Open Graph / Twitter image of the invite page, 1200x630) and
// writes it into the API as a base64 TypeScript module (no image tools needed, no new dependency):
//   node scripts/build-invite-card.mjs
// The same white location pin with a coral dot on the brand violet as the app icon
// (apps/mobile/scripts/build-icons.mjs), with a few quiet rings around it. One generic image for
// every invite: it shows no name, photo or circle (docs/ADR/0009 Ek, 2026-10-22). Change the shape
// or colours here and re-run; commit the result.
import { Buffer } from 'node:buffer';
import { writeFileSync } from 'node:fs';
import process from 'node:process';
import { crc32, deflateSync } from 'node:zlib';

const WIDTH = 1200;
const HEIGHT = 630;
const VIOLET = [0x5b, 0x34, 0xf2];
const WHITE = [0xff, 0xff, 0xff];
const CORAL = [0xff, 0x6a, 0x3d];
const SAMPLES = 4; // supersampling per axis for smooth edges
/** Pin size relative to the image height (the icon script's `scale`). */
const PIN_SCALE = 1;
/** Ring radii and width in pixels, and how much white each one carries. */
const RINGS = [
  { radius: 330, width: 4, alpha: 0.16 },
  { radius: 450, width: 4, alpha: 0.11 },
  { radius: 580, width: 4, alpha: 0.07 },
];

/** Pin in unit coordinates (1 = image height, y down): head circle, tip, hollow centre. */
function pinCoverage(x, y) {
  const head = { x: 0, y: -0.1 * PIN_SCALE, r: 0.27 * PIN_SCALE };
  const tip = { x: 0, y: 0.36 * PIN_SCALE };
  const hole = 0.11 * PIN_SCALE;
  const dx = x - head.x;
  const dy = y - head.y;
  const inHead = dx * dx + dy * dy <= head.r * head.r;
  const d = tip.y - head.y;
  const sin = head.r / d;
  const cos = Math.sqrt(1 - sin * sin);
  const tangentY = head.y + head.r * sin;
  const tangentX = head.r * cos;
  const inTip =
    y >= tangentY && y <= tip.y && Math.abs(x) <= tangentX * ((tip.y - y) / (tip.y - tangentY));
  const inHole = dx * dx + dy * dy <= hole * hole;
  return (inHead || inTip) && !inHole;
}

function dotCoverage(x, y) {
  const dy = y + 0.1 * PIN_SCALE;
  const r = 0.065 * PIN_SCALE;
  return x * x + dy * dy <= r * r;
}

function ringCoverage(px, py) {
  const distance = Math.hypot(px - WIDTH / 2, py - HEIGHT / 2);
  let alpha = 0;
  for (const ring of RINGS) {
    if (Math.abs(distance - ring.radius) <= ring.width / 2) alpha = Math.max(alpha, ring.alpha);
  }
  return alpha;
}

function render() {
  const rows = [];
  for (let py = 0; py < HEIGHT; py++) {
    const row = Buffer.alloc(1 + WIDTH * 3);
    for (let px = 0; px < WIDTH; px++) {
      const sum = [0, 0, 0];
      for (let sy = 0; sy < SAMPLES; sy++) {
        for (let sx = 0; sx < SAMPLES; sx++) {
          const fx = px + (sx + 0.5) / SAMPLES;
          const fy = py + (sy + 0.5) / SAMPLES;
          const x = (fx - WIDTH / 2) / HEIGHT;
          const y = (fy - HEIGHT / 2) / HEIGHT;
          let color = WHITE;
          if (!pinCoverage(x, y)) {
            if (dotCoverage(x, y)) {
              color = CORAL;
            } else {
              const ring = ringCoverage(fx, fy);
              color = VIOLET.map((value, c) => value * (1 - ring) + WHITE[c] * ring);
            }
          }
          for (let c = 0; c < 3; c++) sum[c] += color[c];
        }
      }
      row.set(
        sum.map((value) => Math.round(value / (SAMPLES * SAMPLES))),
        1 + px * 3,
      );
    }
    rows.push(row);
  }
  return Buffer.concat(rows);
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

function png(raw) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(WIDTH, 0);
  header.writeUInt32BE(HEIGHT, 4);
  header.set([8, 2, 0, 0, 0], 8); // 8-bit RGB, no interlace, no transparency
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const image = png(render());
const module = `// GENERATED by scripts/build-invite-card.mjs. Do not edit; change the script and re-run it.
/** The invite card image (${String(WIDTH)}x${String(HEIGHT)} PNG, ${String(image.length)} bytes), base64. */
export const INVITE_CARD_PNG_BASE64 =
  '${image.toString('base64')}';
export const INVITE_CARD_WIDTH = ${String(WIDTH)};
export const INVITE_CARD_HEIGHT = ${String(HEIGHT)};
`;
const out = new URL('../apps/api/src/invite-page/invite-card.ts', import.meta.url);
// eslint-disable-next-line security/detect-non-literal-fs-filename -- one fixed output file inside this repo
writeFileSync(out, module);
process.stdout.write(
  `wrote apps/api/src/invite-page/invite-card.ts (${String(image.length)} bytes of PNG)\n`,
);
